#!/usr/bin/env node
// Bundles data/*.json into data/bundle.js (window.CURVE_DATA) so the page also
// works from file:// where fetch() of local JSON is blocked. Offline.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const web = join(here, "..");
const deep = join(web, "../../bot/knowledge/lanes/token/deep-dive-2026-10-08/sources");
const read = (p) => JSON.parse(readFileSync(p, "utf8"));

const registry = read(join(web, "data/registry.json"));
const specs = Object.fromEntries(registry.curves.map((c) => [c.id, read(join(web, c.spec_file))]));
const snapshot = read(join(web, "data/snapshot.json"));
const verification = read(join(web, "data/weso-curves2.verification.json")).summary;

// Deep-dive reference values (block 30,751,567, 2026-10-08), kept for the
// "API claim" comparison and as a second, independently verified data point.
const sweep = read(join(deep, "cloud-pass/lcd-sweep.json"));
const siteStats = read(join(deep, "site/api/stats.json"));
const sitePrices = read(join(deep, "site/api/prices.json"));
const ci = sweep.weso_state.curve_info.body.data;
const reference = {
 label: "Deep dive 2026-10-08",
 block: sweep.block,
 weso: {
  curve_supply: Number(ci.supply) / 1e6,
  spot_price: Number(ci.spot_price) / 1e6,
  reserve_notional: Number(ci.reserve) / 1e6,
  total_supply: Number(sweep.weso_state.token_info.body.data.total_supply) / 1e6,
 },
 site_stats: { totalSupply: siteStats.totalSupply, burned: siteStats.burned, supply: siteStats.supply },
 site_prices_usd: { WESO: sitePrices.WESO.price, LUNC: sitePrices.LUNC.price, USTC: sitePrices.USTC.price, REBASE: sitePrices.REBASE.price },
 site_prices_note: "weso.world/api/prices and /api/stats as saved in the deep dive (fetched 2026-10-08, about 20:20 UTC)",
};

const bundle = { built_at: new Date().toISOString(), registry, specs, snapshot, reference, verification };
writeFileSync(
 join(web, "data/bundle.js"),
 "// Generated by scripts/build-data.mjs from data/*.json. Do not edit by hand.\nwindow.CURVE_DATA = " +
  JSON.stringify(bundle) +
  ";\n",
);
console.log(`wrote data/bundle.js (${registry.curves.length} curves, snapshot block ${snapshot.block.height})`);
